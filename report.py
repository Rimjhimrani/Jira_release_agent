"""Report writer. The overall decision is computed here from per-requirement decisions (never by the model)."""
from __future__ import annotations
import datetime as dt


def overall(decisions: list[dict]) -> str:
    ds = [d["decision"] for d in decisions]
    if not ds:
        return "NEEDS_REVIEW"
    if "FAIL" in ds:
        return "BLOCKED"
    if "INSUFFICIENT_EVIDENCE" in ds:
        return "NEEDS_REVIEW"
    return "READY"


def build_report(*, project, label, target, req_meta, decisions, tools, usage, errors, elapsed, provider, model,
                 summary_text, jira_base) -> str:
    order = sorted(decisions, key=lambda d: d["requirement_id"])
    ov = overall(order)
    counts = {k: sum(1 for d in order if d["decision"] == k) for k in ("PASS", "FAIL", "INSUFFICIENT_EVIDENCE")}
    L = []
    A = L.append
    A(f"# Release readiness report — {target['service']} {target['release']}\n")
    A(f"**Overall decision: {ov}**  \nPASS {counts['PASS']} · FAIL {counts['FAIL']} · INSUFFICIENT_EVIDENCE {counts['INSUFFICIENT_EVIDENCE']} (of {len(order)} mandatory requirements)\n")
    A(f"- Target build: release `{target['release']}`, commit `{target['commit']}`, service `{target['service']}`, environment `{target['environment']}`, prompt `{target['prompt']}`")
    A(f"- Jira project `{project}`, dataset scope label `{label}`")
    A(f"- Generated {dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')} by provider `{provider}` / model `{model}`\n")
    if provider.startswith("offline"):
        A("> ⚠️ **Generated by the offline rule-based baseline policy, not by an LLM.** Same tools and Jira data path; used to validate the harness. Re-run with `--provider anthropic` for the model-driven report.\n")
    A("## Summary\n")
    A(summary_text.strip() + "\n")
    A("## Decision table\n")
    A("| Req | Requirement | Decision |\n|---|---|---|")
    for d in order:
        A(f"| {d['requirement_id']} | {req_meta.get(d['requirement_id'], {}).get('summary', '').split('] ', 1)[-1]} | **{d['decision']}** |")
    A("\n## Requirement decisions\n")
    for d in order:
        rid = d["requirement_id"]
        m = req_meta.get(rid, {})
        A(f"### {rid} — {m.get('summary', '').split('] ', 1)[-1]}: **{d['decision']}**\n")
        if m.get("criterion"):
            A(f"*Acceptance criterion:* {m['criterion']}\n")
        A(f"{d['rationale']}\n")
        if d.get("supporting_refs"):
            A("**Evidence cited**")
            for ref in d["supporting_refs"]:
                A(f"- {_ref(ref, tools, jira_base)}")
            A("")
        if d.get("rejected_refs"):
            A("**Considered and not relied on**")
            for r in d["rejected_refs"]:
                A(f"- {_ref(r['ref'], tools, jira_base)} — {r['reason']}")
            A("")
        A(f"**Outstanding verification / clarification:** {d.get('outstanding', 'none')}\n")
        if d.get("integrity_notes") and d["integrity_notes"].strip().lower() != "none":
            A(f"**Integrity note:** {d['integrity_notes']}\n")
        if d.get("agent_error"):
            A(f"**Agent/tool failure:** {d['agent_error']}\n")
    A("## Run metrics and limits\n")
    A(f"- Wall-clock: {elapsed:.1f}s · model calls: {usage['model_calls']} · tool calls: {usage['tool_calls']}")
    A(f"- Tokens: {usage['input_tokens']:,} input / {usage['output_tokens']:,} output (model `{model}`)")
    if errors:
        A("- Failures / warnings during the run:")
        for e in errors:
            A(f"  - {e}")
    else:
        A("- No tool or model failures occurred.")
    A("- Evidence source: Jira only (project + dataset label enforced on every query). Native Jira authors/timestamps are importer metadata; the actors/times quoted above are the recorded scenario facts in comment text.")
    return "\n".join(L) + "\n"


def _ref(ref: str, tools, base: str) -> str:
    sid, _, idx = ref.partition("#c")
    key = tools.key_by_src.get(sid, "?")
    row = None
    try:
        row = tools._comments.get(sid, [])[int(idx) - 1]
    except (ValueError, IndexError):
        pass
    url = f"{base}/browse/{key}"
    if row:
        who = f" — {row.get('actor')} ({row.get('role')}), recorded {row.get('timestamp')}"
        return f"[{ref}]({url}?focusedCommentId={row['jira_comment_id']}) (Jira {key}, comment {row['jira_comment_id']}){who}"
    return f"[{ref}]({url}) (Jira {key})"
